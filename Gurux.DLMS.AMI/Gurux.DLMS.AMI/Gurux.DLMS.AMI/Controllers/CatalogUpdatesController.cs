using Gurux.DLMS.AMI.Client.Shared;
using Gurux.DLMS.AMI.Update;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Gurux.DLMS.AMI.Client.Rest;
using Gurux.DLMS.AMI.Db;
using Gurux.Service.Orm;
using Gurux.DLMS.AMI.Shared.DTOs.Manufacturer;
using Gurux.DLMS.AMI.Shared.DTOs;

namespace Gurux.DLMS.AMI.Server.Controllers;

/// <summary>Exposes the configured catalog's latest releases to administrators.</summary>
[ApiController]
[Route("api/Block/CatalogUpdates")]
[Authorize(Roles = GXRoles.Admin)]
public sealed class CatalogUpdatesController(GXCatalogClient catalog, ILogger<CatalogUpdatesController> logger, IDbConnectionFactory database) : ControllerBase
{
    /// <summary>Returns the latest releases with separate product name, version, icon and description fields.</summary>
    [HttpGet("Items")]
    [Produces("application/json")]
    [ResponseCache(NoStore = true, Location = ResponseCacheLocation.None)]
    public async Task<ActionResult<GXCatalogUpdateEntry[]>> Items(CancellationToken cancellationToken = default)
    {
        try
        {
            var products = await catalog.GetAsync(cancellationToken);
            var manufacturers = await ReadManufacturersAsync(cancellationToken);
            return GXCatalogUpdateEntries.Create(products, manufacturers);
        }
        catch (Exception ex) when (ex is HttpRequestException or InvalidDataException or System.Text.Json.JsonException or InvalidOperationException)
        {
            logger.LogWarning(ex, "Cannot read catalog update entries.");
            return Problem("Catalog updates are currently unavailable.", statusCode: StatusCodes.Status502BadGateway);
        }
    }

    /// <summary>Returns an exact retained release, including releases outside the recent list.</summary>
    [HttpGet("Item")]
    [Produces("application/json")]
    [ResponseCache(NoStore = true, Location = ResponseCacheLocation.None)]
    public async Task<ActionResult<GXCatalogUpdateEntry>> Item([FromQuery] string productId, [FromQuery] string version,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(productId) || string.IsNullOrWhiteSpace(version)) {
            return BadRequest();
        }
        try
        {
            var products = await catalog.GetAsync(cancellationToken);
            var item = GXCatalogUpdateEntries.Find(products, await ReadManufacturersAsync(cancellationToken), productId, version);
            return item == null ? NotFound() : item;
        }
        catch (Exception ex) when (ex is HttpRequestException or InvalidDataException or System.Text.Json.JsonException or InvalidOperationException)
        {
            logger.LogWarning(ex, "Cannot read catalog release details.");
            return Problem("Catalog updates are currently unavailable.", statusCode: StatusCodes.Status502BadGateway);
        }
    }

    private async Task<GXManufacturer[]> ReadManufacturersAsync(CancellationToken cancellationToken)
    {
        await using var connection = await database.GetConnectionAsync(cancellationToken);
        var query = GXSelectArgs.Select<GXManufacturer>(m => new { m.Id, m.Name, m.ProfilePicture }, m => m.Removed == null);
        query.Joins.AddLeftJoin<GXManufacturer, GXAppearance>(m => m.ProfilePicture!, a => a.Id);
        query.Columns.Add<GXAppearance>(a => a.Id);
        return [.. await connection.SelectAsync<GXManufacturer>(query, cancellationToken)];
    }

    /// <summary>Returns the RSS feed generated by the catalog publisher.</summary>
    [HttpGet]
    [Produces("application/rss+xml")]
    [ResponseCache(NoStore = true, Location = ResponseCacheLocation.None)]
    public async Task<IActionResult> Get(CancellationToken cancellationToken = default)
    {
        try
        {
            return Content(await catalog.GetFeedAsync(cancellationToken), "application/rss+xml", System.Text.Encoding.UTF8);
        }
        catch (Exception ex) when (ex is HttpRequestException or InvalidDataException or System.Text.Json.JsonException or InvalidOperationException)
        {
            logger.LogWarning(ex, "Cannot read catalog updates.");
            return Problem("Catalog updates are currently unavailable.", statusCode: StatusCodes.Status502BadGateway);
        }
    }
}
